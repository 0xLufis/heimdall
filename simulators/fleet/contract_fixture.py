#!/usr/bin/env python3
"""
Cross-language contract fixture for the simulator -> backend station telemetry path.

Writes the exact protobuf bytes the simulator publishes on `.../plc_memory` (deterministic:
fixed seed, fixed timestamp) to tests/fixtures/simulator/station_blocks.json. Two tests keep the
contract honest from both sides:

* simulators/fleet/test_contract_fixture.py - the committed fixture equals a fresh regeneration,
  so it cannot silently drift from the simulator code;
* tests/backend/.../SimulatorStationBlockContractTests.cs - the real C# `StationTelemetryExtractor`
  recognises every field in those bytes (no hand-copied alias list involved).

Regenerate after changing the station model or the encoding:
    venv/bin/python simulators/fleet/contract_fixture.py --write
"""

from __future__ import annotations

import argparse
import base64
import datetime
import json
import os
import sys
from typing import Any, Dict, List

_here = os.path.dirname(os.path.abspath(__file__))
if _here not in sys.path:
    sys.path.insert(0, _here)

from plc_encoding import FIELD_MAP, build_station_block  # noqa: E402
from station_model import StationProcess, StationSpec  # noqa: E402

FIXTURE_PATH = os.path.normpath(os.path.join(_here, "..", "..", "tests", "fixtures", "simulator", "station_blocks.json"))
FIXED_TIME = datetime.datetime(2026, 1, 15, 8, 30, 0, tzinfo=datetime.timezone.utc)
SEED = 20260115

# (station id, machine type, steps before sampling, scenario applied before the last step)
CASES = [
    ("CONTRACT-CNC-01", "CncMachining", 40, None),
    ("CONTRACT-LASER-01", "LaserWelding", 40, None),
    ("CONTRACT-CONVEYOR-01", "ConveyorTransfer", 40, None),
    ("CONTRACT-ROBOT-01", "RobotCell", 40, "fault"),
    ("CONTRACT-DISPENSER-01", "Dispenser", 40, "maintenance"),
]


def build_cases() -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    for station_id, machine_type, steps, scenario in CASES:
        spec = StationSpec(
            station_id=station_id,
            name=station_id,
            machine_type=machine_type,
            controller_machine_identifier="HW-CONTRACT-IPC",
            cycle_time_target_s=24.0,
        )
        process = StationProcess(spec, seed=SEED)
        for _ in range(steps):
            process.step(2.0)
        if scenario == "fault":
            process.inject_fault()
            process.step(2.0)
        elif scenario == "maintenance":
            process.start_maintenance()
            process.step(2.0)

        sample = process.sample()
        block = build_station_block(station_id, sample, ip_address="10.0.0.5", timestamp=FIXED_TIME)
        numeric = sorted(k for k in FIELD_MAP if sample.get(k) is not None)
        out.append({
            "stationId": station_id,
            "machineType": machine_type,
            "state": sample.get("state"),
            # Model keys of the numeric values present in this block (one extracted metric each).
            "numericFields": numeric,
            "blockBase64": base64.b64encode(block.SerializeToString(deterministic=True)).decode("ascii"),
        })
    return out


def render() -> str:
    doc = {
        "$comment": "GENERATED by simulators/fleet/contract_fixture.py --write. Do not edit by hand.",
        "seed": SEED,
        "timestamp": FIXED_TIME.isoformat(),
        "blocks": build_cases(),
    }
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="(re)write the committed fixture")
    args = parser.parse_args()
    text = render()
    if args.write:
        os.makedirs(os.path.dirname(FIXTURE_PATH), exist_ok=True)
        with open(FIXTURE_PATH, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {FIXTURE_PATH}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
